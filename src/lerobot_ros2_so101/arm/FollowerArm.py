from lerobot.motors.feetech import FeetechMotorsBus, OperatingMode
from lerobot.motors.motors_bus import MotorCalibration
from lerobot.motors import Motor, MotorNormMode

import draccus
from pathlib import Path


class FollowerArm:
    def __init__(self, port=None, calibration_file=None):
        self.port = port
        if not calibration_file:
            raise ValueError("'calibration_file' must point to the follower calibration JSON")

        calibration_path = Path(calibration_file).expanduser()
        if not calibration_path.is_file():
            raise FileNotFoundError(f"Follower calibration file not found: {calibration_path}")

        # Load the JSON generated by `lerobot-calibrate`.
        with (
            calibration_path.open() as f,
            draccus.config_type("json"),
        ):
            self.calibration = draccus.load(dict[str, MotorCalibration], f)

    def connect(self, read_only=False) -> None:
        self.read_only = read_only
        self.bus = FeetechMotorsBus(
            port=self.port,
            motors={
                "shoulder_pan": Motor(1, "sts3215", MotorNormMode.RANGE_0_100),
                "shoulder_lift": Motor(2, "sts3215", MotorNormMode.RANGE_0_100),
                "elbow_flex": Motor(3, "sts3215", MotorNormMode.RANGE_0_100),
                "wrist_flex": Motor(4, "sts3215", MotorNormMode.RANGE_0_100),
                "wrist_roll": Motor(5, "sts3215", MotorNormMode.RANGE_0_100),
                "gripper": Motor(6, "sts3215", MotorNormMode.RANGE_0_100),
            },
            calibration=self.calibration,
        )

        self.bus.connect()
        if read_only:
            actual = self.bus.read_calibration()
            for name, expected in self.calibration.items():
                for field in ('id', 'homing_offset', 'range_min', 'range_max'):
                    if getattr(actual[name], field) != getattr(expected, field):
                        self.bus.disconnect(disable_torque=False)
                        raise ValueError(f'{name}: motor calibration differs from file ({field})')
            return  # No torque, EEPROM, operating-mode or goal writes.

        # SO101Follower.configure()
        with self.bus.torque_disabled():
            # LeRobot calibration defines the encoder home offsets and the
            # physical joint end-stops.  Reapply it on every connection so
            # the ROS/URDF coordinate frame cannot drift from calibration.
            self.bus.write_calibration(self.calibration)
            self.bus.configure_motors()
            for motor in self.bus.motors:
                self.bus.write("Operating_Mode", motor, OperatingMode.POSITION.value)
                self.bus.write("P_Coefficient", motor, 16)
                self.bus.write("I_Coefficient", motor, 0)
                self.bus.write("D_Coefficient", motor, 32)
            # Hold the measured pose when torque is re-enabled, not a stale goal.
            positions = self.bus.sync_read("Present_Position", normalize=False)
            for motor, value in positions.items():
                self.bus.write("Goal_Position", motor, value, normalize=False)

    def read_present_position(self) -> dict[str, float]:
        return self.bus.sync_read("Present_Position", normalize=False)

    def write_goal_position(self, positions) -> None:
        if self.read_only:
            raise RuntimeError('Motor commands are disabled in read-only mode')
        missing = [k for k in positions if k not in self.bus.motors]
        if missing:
            print(f"WARNING: motors not defined. {missing}")
            return
        for k, v in positions.items():
            try:
                self.bus.write("Goal_Position", k, v, normalize=False)
            except RuntimeError as e:
                print(e)
                pass
